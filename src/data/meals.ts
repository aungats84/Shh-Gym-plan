export const MEAL_BY_ID: Record<string, Meal> = Object.fromEntries(MEALS.map((m) => [m.id, m]));

export function mealsForDay(day: number): Meal[] {
  const d = ((day - 1) % 7) + 1;
  return MEALS.filter((m) => m.day === d);
}

export function findOption(optionId: string): { meal: Meal; option: MealOption } | null {
  for (const meal of MEALS) {
    const option = meal.options.find((o) => o.id === optionId);
    if (option) return { meal, option };
  }
  return null;
}

